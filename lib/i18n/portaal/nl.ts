// ---------------------------------------------------------------------------
// Typen. `Woordenboek` is de vorm die elke taal moet hebben (alle teksten als
// string, meervoudsvormen als Meervoud). `Sleutel` en `MvSleutel` zijn de
// geldige paden, zodat t('nav.overzicht') typecheckt en een typfout niet.

type Verbreed<T> = T extends string ? string : T extends { other: string } ? Meervoud : { [K in keyof T]: Verbreed<T[K]> };

export type Woordenboek = Verbreed<typeof nl>;

type Paden<T, P extends string = ''> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : T[K] extends { other: string } ? never : Paden<T[K], `${P}${K}.`>;
}[keyof T & string];

type MvPaden<T, P extends string = ''> = {
  [K in keyof T & string]: T[K] extends string ? never : T[K] extends { other: string } ? `${P}${K}` : MvPaden<T[K], `${P}${K}.`>;
}[keyof T & string];

export type Sleutel = Paden<typeof nl>;
export type MvSleutel = MvPaden<typeof nl>;

